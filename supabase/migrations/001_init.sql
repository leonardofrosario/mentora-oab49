  exists(select 1 from public.simulations s where s.id = simulation_id and s.user_id = auth.uid())
);
create policy "ai own select" on public.ai_interactions for select using (auth.uid() = user_id);
create policy "ai own insert" on public.ai_interactions for insert with check (auth.uid() = user_id);

